#!/usr/bin/env python3
r"""poppler -> lines.json: pdfinfo + pdffonts + pdfimages + pdftotext.

WHY THIS EXISTS. All four tools are already run by pdfdrill, and almost
nothing of what they say survives. Measured on a drilled document's sidecar
(`<pdf>.drill.json`):

    pdfinfo    -> evidence.pdfinfo_fields   the full key/value dict, kept
    pdffonts   -> evidence.font_count       A COUNT
    pdfimages  -> evidence.image_count      A COUNT
    pdftotext  -> evidence.page_count_text  A COUNT

and `font_id` appears nowhere in any lines.json in the library. The
`Document` the docmodel builds holds streams, objects, alignments and a
`meta` bag; none of these four becomes a DocObject. So the richest free
evidence about a born-digital PDF is reduced to three integers, and this
tool writes it as a reading instead.

WHAT IS REAL HERE AND WHAT IS INVENTED. Every reader of the output needs
this distinction, so it is in the file itself under `source.invented`:

    REAL     the text of each line and its page         (pdftotext)
    REAL     page width and height, in points           (pdfinfo)
    REAL     the font table, one entry per font          (pdffonts)
    REAL     the image inventory, per page               (pdfimages -list)
    INVENTED every y, every x, every width and height of a LINE, derived
             from the page box and the line's ordinal; `font_size` likewise

`pdftotext` gives lines and pages and no geometry, so the geometry is a
construction: lines are laid out evenly down the text box in order. It is
honest for ordering and for "which page", and it is wrong for anything
that needs a real box — do not judge ink against it.

EMPTY LINES ARE KEPT. `pdftotext` emits them, they carry the paragraph
structure of the page, and dropping them would renumber every line after
the first blank. An empty line gets its slot, its geometry and
`"text": ""`.

MERGING. A lines.json from here is meant to be merged with a richer one
for the same document (MathPix's, or the glyph reader's). Two rules make
that possible, and both are decisions this file records rather than hides:

  1. EVERY ID IS NAMESPACED. A line is `p<page>l<n>@poppler`, a font is
     `f<n>@poppler`. Nothing here can collide with another source's ids,
     so a merge never has to rename to avoid a clash.
  2. WHEN THE SAME THING IS DESCRIBED TWICE, THE RICHER SOURCE KEEPS ITS
     ID AND THIS ONE LOSES. That is the asymmetry the merge needs: an id
     is a handle other files already point at (a judge's finding, an
     alignment, a report row), and the side with real geometry is the side
     those point at. `--merge-prefer` names the winner explicitly so the
     decision is in the command line and not in a default nobody reads.

PARTIAL DELETION IS SAFE. The four tools read the PDF and delete nothing,
so anything written here can be dropped — a page, a line, the font table —
and regenerated by running the tool again. Nothing downstream may treat
this file as the only copy of anything.

PAGE BY PAGE, FIRST PAGE FIRST (DESIGN D-12.1). A reading must be
producible one page at a time, page 1 before the rest — pdfCraft shows its
first page inside a second, and a format that can only be written whole
cannot do that. Two properties carry it here:

  * `--page N` / `--pages A-B` writes a reading for those pages ALONE. The
    file is complete for the pages it contains and SAYS NOTHING about the
    others: `provenance.pages_read` lists what was read, so an absent page
    is "not claimed", never "empty".
  * the per-page file convention is `<stem>.p<N>.lines.json`, and `merge`
    combines them. A page is the unit, so page 1 can be written, read and
    shown while page 2 is still being produced.

Nothing in the format requires the whole document: `pages` is a list, the
font table is document-wide but additive, and a merge of per-page files
yields exactly the whole-document file — verified, not assumed, by
comparing `--page 1` + `--page 2` merged against the two pages read
together. That is the property a C implementation has to preserve.

POPPLER IS A REFERENCE AND AN ORACLE, NEVER A SOURCE (owner, 2026-11-23,
DESIGN D-12: "use Poppler only as reference, don't copy code"). This file
INVOKES the four tools as programs and reads their printed output; no line
of Poppler's source enters this repository, and none may enter the C
successor either. That successor is to be written from the PDF
specification, with these tools used only to check its answers — which is
what makes this file useful beyond today: it is the shape to match and a
second opinion to test against, not a design to copy.

THE `source` NAMES THE BACKEND (DESIGN D-12.2). pdfdrill chooses its
backend by user configuration — the C tools, MathPix, Gemma4 over REST, or
Makora — and the top-level `source` is that backend's name, per
contracts/reading.md rule 1. `poppler-tools` is this one. A consumer
classifies a reading by that string and never by its shape, so a backend
that writes points where another writes pixels is still read correctly.
"""
from __future__ import annotations

import argparse
import json
import pathlib
import re
import subprocess
import sys

TOOL = "poppler-tools"
#: The producer name, written to the top-level `source` as a STRING
#: (contracts/reading.md rule 1). Consumers classify a reading by it.
SOURCE_NAME = TOOL
DPI = 250.0                  # the corpus convention: lines.json geometry is
PX_PER_PT = DPI / 72.0       # render pixels at 250 dpi, not points


def _run(cmd: list[str]) -> str:
    """Run a poppler tool. Its absence is reported, never guessed around."""
    try:
        p = subprocess.run(cmd, capture_output=True, text=True, timeout=300)
    except FileNotFoundError:
        raise SystemExit("%s is not installed; `pdfdrill doctor` lists the "
                         "tools pdfdrill needs." % cmd[0])
    except subprocess.TimeoutExpired:
        raise SystemExit("%s timed out on this document." % cmd[0])
    if p.returncode != 0 and not p.stdout:
        raise SystemExit("%s failed: %s" % (cmd[0], (p.stderr or "").strip()[:200]))
    return p.stdout


# --------------------------------------------------------------- pdfinfo ---
def read_pdfinfo(pdf: str) -> dict:
    """Every key pdfinfo prints, plus the page box in points.

    `Page size` reads `595.276 x 841.89 pts (A4)`. A document whose pages
    differ in size prints one `Page N size` line per odd page, and this
    takes the default for all of them — stated in `source.invented` rather
    than silently assumed.
    """
    fields: dict[str, str] = {}
    for line in _run(["pdfinfo", "-isodates", pdf]).splitlines():
        if ":" in line:
            k, v = line.split(":", 1)
            fields[k.strip()] = v.strip()
    w = h = None
    m = re.search(r"([\d.]+)\s*x\s*([\d.]+)\s*pts", fields.get("Page size", ""))
    if m:
        w, h = float(m.group(1)), float(m.group(2))
    try:
        pages = int(fields.get("Pages", "0"))
    except ValueError:
        pages = 0
    return {"fields": fields, "width_pt": w, "height_pt": h, "pages": pages}


# -------------------------------------------------------------- pdffonts ---
def read_pdffonts(pdf: str) -> list[dict]:
    """The font table: one entry per font, each with a `font_id`.

    lines.json has `font_size` and no notion of WHICH font, so a reader
    cannot tell a 35px heading from a 35px formula in a different face.
    The ids are assigned here and referenced from every line; `0` is the
    unknown/default font and always exists, because a line whose font this
    tool cannot determine must still carry a valid `font_id`.
    """
    fonts = [{"font_id": 0, "id": "f0@%s" % TOOL, "name": "(unknown)",
              "type": "", "encoding": "", "embedded": None, "subset": None,
              "to_unicode": None, "source": TOOL,
              "note": "the default: pdftotext does not say which font a line is in"}]
    out = _run(["pdffonts", pdf]).splitlines()
    # FIXED-WIDTH COLUMNS, READ FROM THE RULE LINE. `str.split()` is wrong
    # here and the error is quiet: `type` is `Type 1C`, two words, so a
    # whitespace split takes `Type`, loses `1C`, and shifts every later
    # column — `emb`/`sub`/`uni` then read as None for every font. The
    # `---- ----` line under the header states each field's width, so the
    # boundaries come from the output itself rather than from counted
    # characters that a poppler release could move.
    spans: list[tuple] = []
    header = ""
    for i, line in enumerate(out):
        if set(line.strip()) <= set("- ") and "-" in line:
            pos, start = [], None
            for j, ch in enumerate(line):
                if ch == "-" and start is None:
                    start = j
                elif ch != "-" and start is not None:
                    pos.append((start, j)); start = None
            if start is not None:
                pos.append((start, len(line)))
            spans = pos
            header = out[i - 1] if i else ""
            out = out[i + 1:]
            break
    if not spans:
        return fonts
    names = [header[a:b].strip().lower() for a, b in spans]

    def _yn(tok: str):
        return True if tok == "yes" else False if tok == "no" else None

    for line in out:
        if not line.strip():
            continue
        cells = {names[k] if k < len(names) else "col%d" % k:
                 line[a:b].strip() for k, (a, b) in enumerate(spans)}
        if not cells.get("name"):
            continue
        n = len(fonts)
        fonts.append({"font_id": n, "id": "f%d@%s" % (n, TOOL),
                      "name": cells.get("name", ""),
                      "type": cells.get("type", ""),
                      "encoding": cells.get("encoding", ""),
                      "embedded": _yn(cells.get("emb", "")),
                      "subset": _yn(cells.get("sub", "")),
                      "to_unicode": _yn(cells.get("uni", "")),
                      "object": cells.get("object id", "") or cells.get("object", ""),
                      "source": TOOL})
    return fonts


# ------------------------------------------------------------- pdfimages ---
def read_pdfimages(pdf: str) -> dict:
    """`pdfimages -list` per page: the image inventory, as `diagrams`.

    lines.json already carries `diagrams` as flat rectangles per page, and
    an image's own box is NOT in `-list` output — only its pixel size and
    resolution. So the rectangle is invented like the line boxes, and the
    real numbers (width/height in pixels, dpi, colour space, bits) ride
    along beside it where nothing can mistake them for geometry.
    """
    per_page: dict[int, list[dict]] = {}
    out = _run(["pdfimages", "-list", pdf]).splitlines()
    for line in out:
        parts = line.split()
        if len(parts) < 4 or not parts[0].isdigit():
            continue
        page = int(parts[0])
        rec = {"source": TOOL, "num": parts[1] if len(parts) > 1 else "",
               "kind": parts[2] if len(parts) > 2 else ""}
        for key, idx in (("width_px", 3), ("height_px", 4), ("color", 5),
                         ("comp", 6), ("bpc", 7), ("enc", 8),
                         ("interp", 9), ("object", 10), ("id", 11),
                         ("x_dpi", 12), ("y_dpi", 13), ("size", 14)):
            if idx < len(parts):
                rec[key] = parts[idx]
        per_page.setdefault(page, []).append(rec)
    return per_page


# -------------------------------------------------------------- pdftotext ---
def read_pdftotext(pdf: str, pages: int,
                   want: "set | None" = None) -> dict[int, list[str]]:
    r"""The lines of each page, EMPTY ONES INCLUDED.

    `-layout` keeps the printed order and the column spacing; `\f` is
    poppler's page separator. A trailing empty line produced by the
    separator itself is dropped (it is an artefact of the split, not a
    line of the page); every other blank is kept, because it carries the
    page's paragraph structure and dropping it would renumber every line
    after it.
    """
    # D-12.1: only the pages asked for, so page 1 can be produced and shown
    # while the rest of the document is still unread. `-f`/`-l` keep poppler
    # from parsing pages nobody wants.
    cmd = ["pdftotext", "-layout"]
    if want:
        cmd += ["-f", str(min(want)), "-l", str(max(want))]
    txt = _run(cmd + [pdf, "-"])
    chunks = txt.split("\f")
    if chunks and not chunks[-1].strip():
        chunks = chunks[:-1]
    out: dict[int, list[str]] = {}
    first = min(want) if want else 1
    for i, chunk in enumerate(chunks, start=first):
        if want and i not in want:
            continue
        lines = chunk.split("\n")
        if lines and lines[-1] == "":
            lines = lines[:-1]          # the separator's own newline
        out[i] = lines
    # A page poppler emitted nothing for is still a page that was READ, and
      # an empty list says so. A page NOT read is simply absent — the
      # difference is what makes a partial reading honest.
    for p in (sorted(want) if want else range(1, (pages or 0) + 1)):
        out.setdefault(p, [])
    return out


# ---------------------------------------------------------------- geometry ---
def invent_geometry(n: int, total: int, text: str,
                    w_pt: float, h_pt: float) -> dict:
    """A plausible box for line `n` of `total`, in render pixels.

    INVENTED, and the output says so. The text box is the page inset by a
    tenth on each side — poppler gives no margins — and the lines divide it
    evenly. Width follows the character count at a nominal 0.5 em per
    character, clamped to the box. Good enough to order and to place on a
    page; wrong for anything that measures ink.
    """
    pad_x, pad_y = 0.10 * w_pt, 0.08 * h_pt
    box_w, box_h = w_pt - 2 * pad_x, h_pt - 2 * pad_y
    step = box_h / max(total, 1)
    size_pt = min(max(step * 0.62, 6.0), 14.0)
    y_pt = pad_y + n * step
    stripped = text.rstrip()
    indent = len(text) - len(text.lstrip()) if stripped else 0
    x_pt = pad_x + indent * 0.5 * size_pt
    text_w = min(len(stripped) * 0.5 * size_pt, max(box_w - (x_pt - pad_x), 1.0))
    return {"region": {"top_left_x": round(x_pt * PX_PER_PT),
                       "top_left_y": round(y_pt * PX_PER_PT),
                       "width": max(1, round(text_w * PX_PER_PT)),
                       "height": max(1, round(size_pt * PX_PER_PT))},
            "font_size": max(1, round(size_pt * PX_PER_PT))}


def build(pdf: str, want: "set | None" = None) -> dict:
    """The four tools, in one lines.json. `want` limits it to those pages."""
    info = read_pdfinfo(pdf)
    w_pt = info["width_pt"] or 595.276
    h_pt = info["height_pt"] or 841.89
    fonts = read_pdffonts(pdf)
    images = read_pdfimages(pdf)
    text = read_pdftotext(pdf, info["pages"], want)
    stem = pathlib.Path(pdf).stem

    pages = []
    for pno in sorted(text):
        lines = text[pno]
        out_lines = []
        for i, raw in enumerate(lines):
            g = invent_geometry(i, len(lines), raw, w_pt, h_pt)
            body = raw.rstrip()
            out_lines.append({
                "id": "p%dl%d@%s" % (pno, i, TOOL),
                "type": "text",
                "line": i + 1,
                "column": 0,
                # font_size is INVENTED; font_id names the table entry and is
                # 0 because pdftotext does not say which font a line is in.
                "font_size": g["font_size"],
                "font_id": 0,
                "is_printed": True,
                "is_handwritten": False,
                "conversion_output": False,
                "confidence": 1.0 if body else 0.0,
                "confidence_rate": 1.0 if body else 0.0,
                "region": g["region"],
                "cnt": [[g["region"]["top_left_x"], g["region"]["top_left_y"]],
                        [g["region"]["top_left_x"] + g["region"]["width"],
                         g["region"]["top_left_y"]],
                        [g["region"]["top_left_x"] + g["region"]["width"],
                         g["region"]["top_left_y"] + g["region"]["height"]],
                        [g["region"]["top_left_x"],
                         g["region"]["top_left_y"] + g["region"]["height"]]],
                "text": body,
                "text_display": body,
                "children_ids": [],
                # kept so a merge and a reader can tell this line from one
                # that was measured
                "geometry_invented": True,
                "is_empty": not body,
            })
        pages.append({
            "image_id": "%s-%02d" % (stem, pno),
            "page": pno,
            "languages_detected": [],
            "page_width": round(w_pt * PX_PER_PT),
            "page_height": round(h_pt * PX_PER_PT),
            "px_per_pt": PX_PER_PT,
            "source": "poppler-pdftotext",
            "diagrams": [],
            "images": images.get(pno, []),
            "fills": [],
            "links": [],
            "lines": out_lines,
        })

    return {
        # RULE 1 OF contracts/reading.md: the top-level `source` is the
        # PRODUCER'S NAME, a string, and every consumer classifies a reading
        # by it — "decide by the declared producer, never by the shape". An
        # earlier version of this file made it a dict, which breaks that
        # classification for every reader of the field and raised
        # AttributeError in this file's own merge on the first real use.
        # Everything that was in that dict is now `provenance`.
        "source": SOURCE_NAME,
        "provenance": {
            "tool": TOOL,
            "produced_by": "tools/popplerlines.py",
            "tools": ["pdfinfo", "pdffonts", "pdfimages -list", "pdftotext -layout"],
            "pdf": str(pdf),
            "id_namespace": TOOL,
            "backend": TOOL,
            "backends_known": ["poppler-tools", "c-tools", "mathpix",
                               "gemma4-rest", "makora"],
            "pages_read": sorted(text),
            "pages_in_document": info["pages"],
            "partial": bool(want) and len(text) < (info["pages"] or 0),
            "real": ["line text", "page of each line", "page width/height",
                     "font table", "image inventory"],
            "invented": ["every line region (x, y, width, height)",
                         "font_size",
                         "every image rectangle",
                         "one page size for all pages when pdfinfo prints only the default"],
            "merge": {
                "id_form": "p<page>l<n>@%s, f<n>@%s" % (TOOL, TOOL),
                "on_conflict": "the richer source keeps its id; this one loses",
                "deletable": "any page, line or font here may be dropped and "
                             "regenerated: the four tools read the PDF and "
                             "delete nothing",
            },
            "pdfinfo_fields": info["fields"],
        },
        "fonts": fonts,
        "pages": pages,
    }


# ------------------------------------------------------------------ merge ---
def merge(base: dict, add: dict, prefer: str) -> dict:
    """Merge `add` into `base`, page by page, ids namespaced.

    THE DECISION THIS FUNCTION EXISTS TO MAKE EXPLICIT: when both sides
    describe the same page, one side's lines are kept as the page's `lines`
    and the other's are kept beside them under `lines_<namespace>`. The
    winner is `prefer`, named on the command line. The loser keeps its own
    ids — nothing is renamed — so a finding that points at
    `p3l7@poppler` still resolves after the merge.

    Why not interleave them: a line from here has invented geometry and a
    line from a reader has measured geometry, and sorting the two together
    by position would produce an order that is partly real and partly
    fictional, with nothing in the result saying which. Keeping them in
    separate lists keeps that distinction a reader can act on.
    """
    out = json.loads(json.dumps(base))
    # ANOTHER SOURCE'S `source` NEED NOT BE A DICT. The glyph reader writes
    # a plain string there, so asking it for a key raised AttributeError on
    # the first real merge. A merge tool that assumes the other side's shape
    # is not a merge tool.
    def _ns(doc: dict, fallback: str) -> str:
        """The producer name, per contracts/reading.md rule 1: a string.

        A dict is still tolerated rather than crashed on, because files
        written before that rule was settled exist on disk — including the
        first output of this tool. Tolerated, never produced.
        """
        src = doc.get("source")
        if isinstance(src, str) and src.strip():
            return re.sub(r"[^A-Za-z0-9]+", "-", src.strip())[:40]
        if isinstance(src, dict):                     # pre-contract file
            return src.get("id_namespace") or src.get("tool") or fallback
        return fallback

    ns_add = _ns(add, "other")
    ns_base = _ns(out, "base")
    out.setdefault("fonts", [])
    seen = {(f.get("name"), f.get("type")) for f in out["fonts"]}
    for f in add.get("fonts") or []:
        if (f.get("name"), f.get("type")) not in seen:
            out["fonts"].append(f)          # ids already namespaced: no clash
    by_page = {p.get("page"): p for p in out.get("pages") or []}
    for p in add.get("pages") or []:
        n = p.get("page")
        if n not in by_page:
            out.setdefault("pages", []).append(p)
            continue
        tgt = by_page[n]
        winner = ns_add if prefer == ns_add else ns_base
        loser_lines = p["lines"] if winner == ns_base else tgt["lines"]
        if winner == ns_add:
            tgt["lines"] = p["lines"]
        tgt["lines_%s" % (ns_add if winner == ns_base else ns_base)] = loser_lines
        for k in ("images", "diagrams", "links", "fills"):
            if p.get(k):
                tgt.setdefault(k, []).extend(p[k])
    out.setdefault("merged", []).append(
        {"from": ns_add, "preferred": prefer,
         "note": "the preferred side owns `lines`; the other is kept under "
                 "`lines_<namespace>` with its ids intact"})
    return out


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(
        description="poppler (pdfinfo+pdffonts+pdfimages+pdftotext) -> lines.json")
    ap.add_argument("pdf")
    ap.add_argument("-o", "--out",
                    help="default <stem>.poppler.lines.json, or "
                         "<stem>.p<N>.lines.json for a single page")
    ap.add_argument("--page", type=int,
                    help="read ONLY this page (D-12.1: first page first)")
    ap.add_argument("--pages", metavar="A-B",
                    help="read only this inclusive page range")
    ap.add_argument("--merge-into", metavar="LINES_JSON",
                    help="merge the result into this existing lines.json")
    ap.add_argument("--merge-prefer", default=TOOL,
                    help="which namespace owns `lines` on a shared page "
                         "(default: %s, i.e. this tool loses nothing only "
                         "because it is alone; name the other side to let it win)"
                         % TOOL)
    a = ap.parse_args(argv)
    if not pathlib.Path(a.pdf).is_file():
        raise SystemExit("not a file: %s" % a.pdf)

    want = None
    if a.page:
        want = {a.page}
    elif a.pages:
        m = re.match(r"^(\d+)\s*-\s*(\d+)$", a.pages.strip())
        if not m:
            raise SystemExit("--pages wants A-B, e.g. --pages 1-4")
        want = set(range(int(m.group(1)), int(m.group(2)) + 1))
    doc = build(a.pdf, want)
    if a.merge_into:
        base = json.loads(pathlib.Path(a.merge_into).read_text(encoding="utf-8"))
        doc = merge(base, doc, a.merge_prefer)

    stem_path = str(pathlib.Path(a.pdf).with_suffix(""))
    # D-12.1: a single page gets the per-page name, so pages can be written
    # independently and merged later without any of them overwriting another.
    default = ("%s.p%d.lines.json" % (stem_path, a.page) if a.page
               else stem_path + ".poppler.lines.json")
    out = a.out or default
    pathlib.Path(out).write_text(json.dumps(doc, indent=1, ensure_ascii=False),
                                 encoding="utf-8")
    npages = len(doc.get("pages") or [])
    nlines = sum(len(p.get("lines") or []) for p in doc.get("pages") or [])
    nempty = sum(1 for p in doc.get("pages") or []
                 for l in (p.get("lines") or []) if l.get("is_empty"))
    nimg = sum(len(p.get("images") or []) for p in doc.get("pages") or [])
    print("wrote %s" % out)
    print("  %d page(s), %d line(s) (%d empty, kept), %d font(s), %d image(s)"
          % (npages, nlines, nempty, len(doc.get("fonts") or []), nimg))
    prov = doc.get("provenance") or {}
    if prov.get("pages_read") is not None:
        print("  pages read: %s of %s%s"
              % (prov.get("pages_read"), prov.get("pages_in_document"),
                 "  (PARTIAL: absent pages are not claimed)"
                 if prov.get("partial") else ""))
    print("  REAL: text, page, page size, font table, image inventory")
    print("  INVENTED: every line region and font_size — see provenance.invented")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
