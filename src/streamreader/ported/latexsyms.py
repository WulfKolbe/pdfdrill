"""latexsyms - glyph -> (LaTeX command, class), derived from LaTeX itself.

CONTRACT
    table() -> {(FAMILY, glyph_name): (command, cls)}
        FAMILY as mathsym.fam ('CMSY', 'MSAM', ...); cls as mathsym
        ('rel' 'bin' 'ord' 'bigop' 'open' 'close' 'punct')
    Source: every \\DeclareMathSymbol in fontmath.ltx (CM) and amssymb.sty
    (AMS), e.g. \\DeclareMathSymbol{\\triangleq}{\\mathrel}{AMSa}{"2C}; the
    glyph name at that code comes from the font's own Type 1 encoding
    (msam10.pfb: code "2C = 'defines'). The first declaration of a glyph
    wins. Nothing is hand-written.
    pdf2mmd2: table() is the generated latexsyms_table (no TeX Live at run
    time); from_tex() reads the files, {} when they are missing;
    `python -m pdf2mmd2.ported.latexsyms` regenerates the table.
"""
from __future__ import annotations

import functools, re, shutil, subprocess

SYMFONT = {"operators": ("CMR", "cmr10"), "letters": ("CMMI", "cmmi10"),
           "symbols": ("CMSY", "cmsy10"), "largesymbols": ("CMEX", "cmex10"),
           "AMSa": ("MSAM", "msam10"), "AMSb": ("MSBM", "msbm10")}
CLASS = {"\\mathrel": "rel", "\\mathbin": "bin", "\\mathord": "ord", "\\mathalpha": "ord",
         "\\mathop": "bigop", "\\mathopen": "open", "\\mathclose": "close", "\\mathpunct": "punct"}
_DECL = re.compile(r"\\DeclareMathSymbol\{?(\\[A-Za-z]+)\}?\s*\{(\\math[a-z]+)\}\s*\{(\w+)\}\s*\{([^}]+)\}")


def _kpse(name):
    if not shutil.which("kpsewhich"):
        return ""
    return subprocess.run(["kpsewhich", name], capture_output=True, text=True).stdout.strip()


@functools.lru_cache(maxsize=None)
def _code_to_name(font):
    p = _kpse(font + ".pfb")
    if not p:
        return {}
    out = {}
    for c, n in re.findall(rb"dup (\d+) ?/([A-Za-z0-9.]+) put", open(p, "rb").read()):
        out.setdefault(int(c), n.decode())
    return out


def _code(s):
    s = s.strip()
    if s.startswith('"'):
        return int(s[1:], 16)
    if s.startswith("'"):
        return int(s[1:], 8)
    if s.startswith("`"):
        return ord(s[-1])
    return int(s)


@functools.lru_cache(maxsize=None)
def table() -> dict:
    # pdf2mmd2: generated once into code (fontmath.ltx and amssymb.sty have
    # not changed in decades); no kpsewhich, no file per worker process
    from .latexsyms_table import TABLE
    return TABLE


def from_tex() -> dict:
    """The table as LaTeX gives it now; {} without TeX Live."""
    out = {}
    for f in ("fontmath.ltx", "amssymb.sty"):
        p = _kpse(f)
        if not p:
            continue
        for cmd, cls, sym, code in _DECL.findall(open(p, encoding="latin-1").read()):
            if sym not in SYMFONT or cls not in CLASS:
                continue
            fam, font = SYMFONT[sym]
            try:
                name = _code_to_name(font).get(_code(code))
            except ValueError:
                continue
            if name:
                out.setdefault((fam, name), (cmd, CLASS[cls]))
    return out


def source() -> str:
    t = from_tex()
    if not t:
        raise SystemExit("no fontmath.ltx/amssymb.sty in this TeX installation")
    rows = "".join(f"    {k!r}: {v!r},\n" for k, v in sorted(t.items()))
    return ("# Generated by python -m pdf2mmd2.ported.latexsyms - do not edit.\n"
            "# (FAMILY, glyph name) -> (command, class), from every\n"
            "# \\DeclareMathSymbol of fontmath.ltx and amssymb.sty.\n"
            "TABLE = {\n" + rows + "}\n")


if __name__ == "__main__":       # python -m pdf2mmd2.ported.latexsyms [OUT]
    import os, sys
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
        os.path.dirname(os.path.abspath(__file__)), "latexsyms_table.py")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write(source())
    print(len(from_tex()), "symbols written to", out)
