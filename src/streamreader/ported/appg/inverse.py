"""L3 - inverse of Appendix G rules: PDF glyphs -> hypotheses (rule, style,
nucleus kind) with the residual. First rule: 18 (scripts on a character).

Glyph input = what the PDF gives: dict(font, glyph, size, base) - font name
without subset prefix ('cmr7'), Type 1 glyph name ('two'), size and baseline
in bp. P = L0 params (the document's font setup hypothesis: sigma/xi/sizes).

CONTRACT
    metrics(font, glyph, size_bp) -> dict(w, h, d, ic) in pt, or None
      TFM of `font` at the glyph's size (size_bp in pt, rounded to 0.01 pt),
      slot from the .pfb built-in encoding - both from appg.fontdata
      (generated by tools/gen_tables.py; no runtime read; a font outside
      gen_tables.FONTS gives None) - the lowest slot that the
      TFM has, as CM encodings name some glyphs twice (minus at 0 and 161);
      None if either is missing.
    size_class(size_bp, P) -> 'text' | 'script' | 'scriptscript' (nearest P['sizes'])
    rule18(base, script, P, partner=None, tol_bp=0.01) -> [hypothesis]
      One hypothesis per style C of the base's size class (text: D D' T T';
      script: S S'; scriptscript: SS SS'), assuming a character nucleus
      (Rule 18a, u = v = 0):
        rel = 'sup' if the script's baseline is above the base's, else 'sub'
        both = partner given (the other script of the same base): the
          prediction then uses both boxes (18d/18e) and `fit` requires both
          observed shifts within tol_bp
        pred_bp / res_bp = predicted shift / observed - predicted, for the script
        steps = forward.rule18 steps
        pred_x_bp / res_x_bp = horizontal offset of the script from the base
          origin (forward.rule18_x: base width, + italic correction for a sup)
        fit = |res| <= tol_bp and |res_x| <= tol_bp (and the partner's both)
      Glyphs need x0 (bp) too. [] when a glyph's metrics (base included) are unknown. Ambiguity is reported, not
      resolved: a subscript alone fits every text style alike.
"""
import base64, functools
from . import PT_TO_BP, forward as F
from . import tfm, fontdata

_TEXT = {"text": ("D", "D'", "T", "T'"), "script": ("S", "S'"), "scriptscript": ("SS", "SS'")}


@functools.lru_cache(None)
def _enc(font):
    """glyph name -> all slots naming it (CM encodings repeat slots 0-32 above 160)."""
    return fontdata.ENC.get(font)


@functools.lru_cache(None)
def _tfm(font, at_pt):
    b = fontdata.TFM.get(font)
    return tfm.loads(base64.b64decode("".join(b)), size_sp=round(at_pt * 65536), name=font) if b else None


def metrics(font, glyph, size_bp):
    enc = _enc(font)
    if not enc or glyph not in enc:
        return None
    f = _tfm(font, round(size_bp / PT_TO_BP, 2))
    slots = [c for c in enc[glyph] if f is not None and c in f.chars]
    if not slots:
        return None
    c = f.chars[slots[0]]
    return dict(w=c.width / 65536, h=c.height / 65536, d=c.depth / 65536, ic=c.italic / 65536)


def size_class(size_bp, P):
    pt = size_bp / PT_TO_BP
    return min(P["sizes"], key=lambda s: abs(P["sizes"][s] - pt))


def rule18(base, script, P, partner=None, tol_bp=0.01):
    m = metrics(script["font"], script["glyph"], script["size"])
    mp = metrics(partner["font"], partner["glyph"], partner["size"]) if partner else None
    mb = metrics(base["font"], base["glyph"], base["size"])
    if m is None or mb is None or (partner and mp is None):
        return []
    dy = script["base"] - base["base"]
    rel = "sup" if dy > 0 else "sub"
    sup, sub = (m, mp) if rel == "sup" else (mp, m)
    xs = F.rule18_x(mb["w"], mb["ic"], sup is not None, sub is not None)
    px = xs[rel] * PT_TO_BP
    res_x = (script["x0"] - base["x0"]) - px
    pxp = xs["sub" if rel == "sup" else "sup"] * PT_TO_BP if partner else None
    out = []
    for C in _TEXT[size_class(base["size"], P)]:
        r = F.rule18(dict(char=True, h=0.0, d=0.0), sup and dict(h=sup["h"], d=sup["d"]),
                     sub and dict(h=sub["h"], d=sub["d"]), C, P)
        pred = (r["u"] if rel == "sup" else r["v"]) * PT_TO_BP
        res = abs(dy) - pred
        ok = abs(res) <= tol_bp and abs(res_x) <= tol_bp
        if partner:
            pp = (r["v"] if rel == "sup" else r["u"]) * PT_TO_BP
            ok = ok and abs(abs(partner["base"] - base["base"]) - pp) <= tol_bp \
                and abs((partner["x0"] - base["x0"]) - pxp) <= tol_bp
        out.append(dict(rule="18", rel=rel, C=C, nuc="char", both=bool(partner), steps=r["steps"],
                        pred_bp=pred, res_bp=res, pred_x_bp=px, res_x_bp=res_x, fit=ok))
    return sorted(out, key=lambda h: abs(h["res_bp"]))
