"""Generate the code tables that replace runtime reads of fonts and TeX runs.

    python -m pdf2mmd2.ported.appg.gen_tables [OUTDIR]   (default: this package)

Writes, deterministically (same sources -> same bytes):
  fontdata.py         ENC {font: {glyph: [slots]}} from each font's .pfb
                      built-in encoding; TFM {font: base64 of the .tfm bytes}
                      - for FONTS.
  setup_article10.py  SETUP = fonts, sizes, sigma, xi of texroles' LaTeX
                      setup from one params.load() run (needs lualatex).
The sources are read HERE only (kpsewhich for fonts); the library imports
the generated modules: no file read and no TeX at run time. The tables are
TeX Live's Computer Modern and AMS fonts, unchanged for decades, so they are
generated once and committed; tests/ported/test_appg_tables.py regenerates
and compares.
"""
import base64, collections, os, subprocess, sys

from . import pfbenc

FONTS = sorted({f"{fam}{s}" for fam in ("cmr", "cmmi", "cmsy", "cmbx", "cmmib", "cmbsy", "eufm", "msam", "msbm")
                for s in (5, 7, 10)} | {"cmex7", "cmex10", "cmti10", "cmsl10", "cmtt10", "cmss10", "cmmib10"})
_HEAD = "# Generated by pdf2mmd2.ported.appg.gen_tables - do not edit.\n"


def kpse(name):
    try:
        return subprocess.check_output(["kpsewhich", name], text=True).strip() or None
    except subprocess.CalledProcessError:
        return None


def fontdata():
    enc, tfm = {}, {}
    for f in FONTS:
        p, t = kpse(f + ".pfb"), kpse(f + ".tfm")
        if not (p and t):
            continue
        d = collections.defaultdict(list)
        for c, n in sorted(pfbenc.encoding(p).items()):
            d[n].append(c)
        enc[f] = dict(sorted(d.items()))
        tfm[f] = base64.b64encode(open(t, "rb").read()).decode()
    src = (_HEAD + "# ENC: .pfb built-in encodings (glyph name -> slots); TFM: base64 .tfm bytes (TeX Live).\n")
    src += "ENC = {\n" + "".join(f"    {f!r}: {enc[f]!r},\n" for f in sorted(enc)) + "}\n"
    src += "TFM = {\n"
    for f in sorted(tfm):
        s = tfm[f]
        src += f"    {f!r}: (\n" + "".join(f"        {s[i:i + 76]!r}\n" for i in range(0, len(s), 76)) + "    ),\n"
    return src + "}\n"


def setup():
    import tempfile
    from . import params
    with tempfile.TemporaryDirectory() as d:
        t = params.load(d)
    S = {k: t[k] for k in ("fonts", "sizes")}
    S.update(sigma={s: dict(sorted(v.items())) for s, v in sorted(t["sigma"].items())},
             xi={s: dict(sorted(v.items())) for s, v in sorted(t["xi"].items())})
    return (_HEAD.rstrip("\n") + " From params.load() (LuaTeX, article 10pt, amsmath).\n"
            "SETUP = {\n" + "".join(f"    {k!r}: {S[k]!r},\n" for k in ("fonts", "sizes", "sigma", "xi")) + "}\n")


def main(argv):
    out = argv[0] if argv else os.path.dirname(os.path.abspath(__file__))
    os.makedirs(out, exist_ok=True)
    open(os.path.join(out, "fontdata.py"), "w", encoding="utf-8").write(fontdata())
    open(os.path.join(out, "setup_article10.py"), "w", encoding="utf-8").write(setup())
    print("written to", out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
