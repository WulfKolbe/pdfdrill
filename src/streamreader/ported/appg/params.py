"""L0 - TeX facts, read from TeX (never typed in by hand).

CONTRACT
    load(workdir) -> dict(
        sizes  {size: pt}                   at-size of the family-2 font at that size
        fonts  {"<fam>/<size>": tfm name}   size in text|script|scriptscript, every
                                             family 0..15 that has a font
        sigma  {size: {1..22: pt}}           \\fontdimen n of family 2 at that size (LuaTeX font
                                             tables; printed with TeX's print_scaled)
        xi     {size: {1..13: pt}}           \\fontdimen n of family 3
        chars  {"<fam>/<size>": {code: (wd, ht, dp, ic) pt}} codes 0..127 that exist
      ) from one lualatex run of texroles' preamble (article, amsmath, amssymb),
      cached as JSON in workdir. RuntimeError when the run gives no data.
    default() -> dict(fonts, sizes, sigma, xi) of texroles' setup, stored in
      code (appg/setup_article10.py, generated by tools/gen_tables.py from a
      load() run; a test compares it with a live run). No file, no TeX run.
    to_bp(pt) -> bp
"""
import json, os, re, subprocess
from . import PT_TO_BP

SIZES = ("text", "script", "scriptscript")
_PRE = "\\documentclass{article}\\usepackage{amsmath,amssymb}\\pagestyle{empty}\n"
_LUA = r"""
local NAMES = {"slant","space","space_stretch","space_shrink","x_height","quad","extra_space"}
  local function prm(f, n) local p = f.parameters or {}; return p[NAMES[n] or n] or p[n] or 0 end
  for sz, name in pairs({[0]="text", [1]="script", [2]="scriptscript"}) do
    for fam = 0, 15 do
      local id = node.family_font(fam, sz)
      local f = id and id > 0 and font.getfont(id)
      if f then
      texio.write_nl("FJFONT " .. fam .. "/" .. name .. " " .. (f.name or "?"))
      if fam == 2 then texio.write_nl("FJSIZE " .. name .. " " .. (f.size or 0)) end
      if fam == 2 then for n = 1, 22 do texio.write_nl("FJSIGMA " .. name .. " " .. n .. " " .. prm(f, n)) end end
      if fam == 3 then for n = 1, 13 do texio.write_nl("FJXI " .. name .. " " .. n .. " " .. prm(f, n)) end end
      for c = 0, 127 do local ch = f.characters[c]
        if ch then texio.write_nl(string.format("FJCHAR %d/%s %d %d %d %d %d", fam, name, c,
          ch.width or 0, ch.height or 0, ch.depth or 0, ch.italic or 0)) end end
      end
    end
  end
"""
_BODY = r"""
\begin{document}
$\relax$
\directlua{dofile("fjparams.lua")}
\end{document}
"""


def scaled(sp):
    """TeX's print_scaled (tex.web par. 103): sp -> the decimal \\the prints, as float."""
    neg = sp < 0
    sp = abs(sp)
    out = str(sp // 65536) + "."
    s, delta = 10 * (sp % 65536) + 5, 10
    while True:
        if delta > 65536:
            s = s + 0x8000 - 50000
        out += chr(ord("0") + s // 65536)
        s, delta = 10 * (s % 65536), delta * 10
        if s <= delta:
            break
    return -float(out) if neg else float(out)


def default():
    from .setup_article10 import SETUP
    return dict(fonts=dict(SETUP["fonts"]), sizes=dict(SETUP["sizes"]),
                sigma={s: dict(v) for s, v in SETUP["sigma"].items()}, xi={s: dict(v) for s, v in SETUP["xi"].items()})


def to_bp(pt):
    return pt * PT_TO_BP


def load(workdir):
    os.makedirs(workdir, exist_ok=True)
    cache = os.path.join(workdir, "appg_params.json")
    if os.path.exists(cache):
        return _fix(json.load(open(cache)))
    open(os.path.join(workdir, "p.tex"), "w").write(_PRE + _BODY)
    open(os.path.join(workdir, "fjparams.lua"), "w").write(_LUA)
    subprocess.run(["lualatex", "-interaction=nonstopmode", "p.tex"], cwd=workdir,
                   capture_output=True, timeout=300)
    log = open(os.path.join(workdir, "p.log"), errors="replace").read()
    out = dict(fonts={}, sizes={}, sigma={s: {} for s in SIZES}, xi={s: {} for s in SIZES}, chars={})
    for s, v in re.findall(r"FJSIZE (\w+) (\d+)", log):
        out["sizes"][s] = scaled(int(v))
    for k, name in re.findall(r"FJFONT (\d+/\w+) (\S+)", log):
        out["fonts"][k] = name
    for s, n, v in re.findall(r"FJSIGMA (\w+) (\d+) (-?\d+)", log):
        out["sigma"][s][int(n)] = scaled(int(v))
    for s, n, v in re.findall(r"FJXI (\w+) (\d+) (-?\d+)", log):
        out["xi"][s][int(n)] = scaled(int(v))
    for k, c, w, h, d, i in re.findall(r"FJCHAR (\d+/\w+) (\d+) (-?\d+) (-?\d+) (-?\d+) (-?\d+)", log):
        out["chars"].setdefault(k, {})[int(c)] = tuple(scaled(int(x)) for x in (w, h, d, i))
    if not out["sigma"]["text"] or not out["chars"]:
        raise RuntimeError(f"no TeX data; see {workdir}/p.log")
    json.dump(out, open(cache, "w"))
    return out


def _fix(d):   # JSON turns int keys into strings
    d["sigma"] = {s: {int(k): v for k, v in t.items()} for s, t in d["sigma"].items()}
    d["xi"] = {s: {int(k): v for k, v in t.items()} for s, t in d["xi"].items()}
    d["chars"] = {f: {int(k): tuple(v) for k, v in t.items()} for f, t in d["chars"].items()}
    return d
