"""Generate one module per font with the metrics `tfm.metrics` needs (T-0038).

    python -m pdf2mmd2.ported.fontmetrics.gen [OUTDIR]   (default: this package)

The values are read exactly as `tfm` reads them at run time otherwise
(kpsewhich + the .pfb encoding, tftopl), so a font's module gives the same
numbers bit for bit. FONTS are the fonts with TeX metrics that pdf2mmd2's
corpus, its twins and the books met (the tfm cache of 2026-10-18). TeX
Live's Computer Modern, AMS, txfonts, pxfonts and their kin have not
changed in a decade: generated once and committed, a lookup costs one
import of a small module instead of two programs or a cache file.
tests/ported/test_fontmetrics.py regenerates and compares.
"""
import os, sys

from . import FONTS, module


def source(font):
    from .. import tfm
    enc, chars = tfm._encoding(font), tfm._chars(font)
    if not (enc and chars):
        raise SystemExit(f"{font}: no metrics in this TeX installation")
    return ("# Generated by pdf2mmd2.ported.fontmetrics.gen - do not edit.\n"
            f"# {font}: ENC glyph name -> code (first slot), CHARS code -> metrics in em.\n"
            f"ENC = {dict(sorted(enc.items()))!r}\n"
            f"CHARS = {dict(sorted(chars.items()))!r}\n")


def main(argv):
    out = argv[0] if argv else os.path.dirname(os.path.abspath(__file__))
    os.makedirs(out, exist_ok=True)
    for f in FONTS:
        with open(os.path.join(out, module(f) + ".py"), "w", encoding="utf-8") as fh:
            fh.write(source(f))
    print(len(FONTS), "fonts written to", out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
